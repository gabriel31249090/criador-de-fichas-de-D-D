const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 let tests=0;
 const check=(cond,message)=>{assert.ok(cond,message);tests++;console.log('PASS',message);};
 for(const viewport of [{width:1365,height:850},{width:390,height:844}]){
  const context=await browser.newContext({viewport,acceptDownloads:true});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.goto('http://127.0.0.1:8091/index.html',{waitUntil:'load'});
  await page.waitForTimeout(900);
  check(await page.locator('[data-tab="compendium"]').count()===1,'Biblioteca abriu no tamanho '+viewport.width);
  check(await page.evaluate(()=>window.DNDCompendium.getSpecies().includes('Aasimar')),'Aasimar cadastrado');
  await page.locator('[data-tab="compendium"]').click();
  await page.locator('[data-cx-species="Aasimar"]').click();
  const race=await page.evaluate(()=>({f:window.DNDDebug.getMutableState().fields.race,sel:document.getElementById('race').value,edition:window.DNDDebug.getMutableState().fields.rulesEdition}));
  check(race.f==='Aasimar'&&race.sel==='Aasimar'&&race.edition==='2024','Aasimar aplicado na ficha original');
  await page.evaluate(()=>{const a=window.DNDDebug,s=a.getMutableState();a.setField('className','Guerreiro');s.fields.level='5';s.abilities.con='14';a.recalc();});
  check(await page.locator('#hpMax').innerText()==='44','PV de guerreiro nível 5, Constituição +2');
  await page.locator('#cxBgA').selectOption('con');await page.locator('#cxBgB').selectOption('str');
  check(await page.locator('#hpMax').innerText()==='49','2024: antecedentes recalculam PV (+2 CON)');
  await page.locator('[data-cx-tab="spells"]').click();
  const cnt=await page.evaluate(()=>window.DNDCompendium.getSpellCount());
  check(cnt>=20,'Catálogo de truques e magias está disponível');
  await page.locator('#cxSearch').fill('Mísseis Mágicos');
  check((await page.locator('[data-cx-spell-card="Mísseis Mágicos"]').innerText()).includes('3 × (1d4+1)'),'Mísseis Mágicos exibe dados e efeitos');
  await page.locator('[data-cx-spell-card="Mísseis Mágicos"] summary').click();
  await page.locator('[data-cx-roll-spell="Mísseis Mágicos"]').click();
  check((await page.locator('[data-cx-result-spell="Mísseis Mágicos"]').innerText()).includes('Total:'),'Rolagem de projéteis registra os resultados');
  await page.locator('[data-cx-spell="Mísseis Mágicos"]').click();
  check(await page.evaluate(()=>window.DNDDebug.getMutableState().v5.selectedSpells.includes('Mísseis Mágicos')),'Magia adicionada à ficha');
  await page.locator('#cxSearch').fill('Rajada Mística');
  await page.locator('[data-cx-spell-card="Rajada Mística"] summary').click();
  check((await page.locator('[data-cx-spell-card="Rajada Mística"]').innerText()).includes('2 × (1d10)'),'Rajada Mística escala para dois feixes no nível 5');
  await page.locator('[data-cx-roll-spell="Rajada Mística"]').click();
  check((await page.locator('[data-cx-result-spell="Rajada Mística"]').innerText()).includes('Total:'),'Rolagem de raios com ataques separados funciona');
  await page.locator('#cxSearch').fill('Invisibilidade');
  check((await page.locator('[data-cx-spell-card="Invisibilidade"]').first().innerText()).includes('Não causa dano'),'Magia utilitária deixa claro que não causa dano');
  await page.locator('[data-cx-tab="gear"]').click();
  await page.locator('#cxSearch').fill('Espada longa');
  check((await page.locator('[data-cx-gear-card="Espada longa"]').innerText()).includes('1d10 com duas mãos'),'Espada longa exibe dano versátil e efeito');
  await page.locator('[data-cx-gear-card="Espada longa"] summary').click();
  await page.locator('[data-cx-roll-gear="Espada longa"]').click();
  check((await page.locator('[data-cx-result-gear="Espada longa"]').innerText()).includes('Ataque:'),'Rolagem de arma mostra ataque e dano');
  await page.locator('[data-cx-gear="Espada longa"]').click();
  check(await page.evaluate(()=>window.DNDDebug.getMutableState().attacks.some(a=>a.name==='Espada longa')),'Arma entrou automaticamente nos ataques');
  check(await page.evaluate(()=>window.DNDDebug.getMutableState().items.some(a=>a.name==='Espada longa')),'Arma entrou automaticamente no inventário');
  await page.locator('#cxSearch').fill('Poção de cura');
  await page.locator('[data-cx-gear-card="Poção de cura"] summary').click();
  await page.locator('[data-cx-roll-gear="Poção de cura"]').click();
  check((await page.locator('[data-cx-result-gear="Poção de cura"]').innerText()).includes('PV recuperáveis'),'Rolagem de poção exibe dados de cura');
  await page.locator('[data-cx-tab="spells"]').click();
  const catalog=await page.evaluate(()=>{
    const p=window.DNDPHB2014;
    return {all:window.DNDV5.SPELLS.length,baseline:p.baseNames().length,fiend:p.expandedNames('Corruptor').length,
      archfey:p.expandedNames('Arquifada').length,oldOne:p.expandedNames('Grande Antigo').length,
      hasSpell:!!window.DNDSpellDetails.get('Fome de Hadar')};
  });
  check(catalog.baseline===74&&catalog.fiend===10&&catalog.archfey===10&&catalog.oldOne===10,'Lista completa: 74 magias básicas + 3 patronos de 10');
  check(catalog.all>=140,'Catálogo ampliado: pelo menos 140 magias 2014');
  check(catalog.hasSpell,'Fome de Hadar tem efeito e dados detalhados');
  await page.locator('#cxSpellClass').selectOption('Bruxo');
  check(await page.locator('#cxPatron').count()===1,'Filtro de patrono aparece para o Bruxo');
  await page.locator('#cxSearch').fill('Braços de Hadar');
  check(await page.locator('[data-cx-spell-card="Braços de Hadar"]').count()===1,'Braços de Hadar é opção básica do Bruxo');
  check((await page.locator('[data-cx-spell-card="Braços de Hadar"]').innerText()).includes('2d6 necrótico'),'Braços de Hadar exibe dano e explicação');
  await page.locator('[data-cx-spell="Braços de Hadar"]').click();
  check(await page.evaluate(()=>window.DNDDebug.getMutableState().v5.selectedSpells.includes('Braços de Hadar')),'Magia do Bruxo registrada na ficha');
  await page.locator('#cxSearch').fill('Bola de Fogo');
  check(await page.locator('[data-cx-spell-card="Bola de Fogo"]').count()===0,'Bruxo sem patrono não vê Bola de Fogo');
  await page.locator('#cxPatron').selectOption('Corruptor');
  check(await page.evaluate(()=>window.DNDDebug.getMutableState().v5.subclasses.Bruxo==='Corruptor'),'Patrono Corruptor persistido');
  check(await page.locator('[data-cx-spell-card="Bola de Fogo"]').count()===1,'Corruptor libera Bola de Fogo');
  check((await page.locator('[data-cx-spell-card="Bola de Fogo"]').innerText()).includes('Patrono: Corruptor'),'Magia expandida rotulada por patrono');
  await page.locator('#cxPatron').selectOption('Arquifada');
  check(await page.locator('[data-cx-spell-card="Bola de Fogo"]').count()===0,'Arquifada não recebe Bola de Fogo');
  await page.locator('#cxSearch').fill('Dedo da Morte');
  check(await page.locator('[data-cx-spell-card="Dedo da Morte"]').count()===1,'Arcanos Místicos aparecem separados');
  check((await page.locator('[data-cx-spell-card="Dedo da Morte"]').innerText()).includes('Arcano Místico'),'Arcano Místico identificado');
  await page.locator('#cxSpellClass').selectOption('Mago');
  await page.locator('#cxSearch').fill('Chuva de Meteoros');
  check(await page.locator('[data-cx-spell-card="Chuva de Meteoros"]').count()===1,'Lista de dano de Mago ampliada pelo livro');
  await page.locator('[data-cx-tab="dm"]').click();
  await page.locator('[data-cx-action="encounter"]').click();
  check((await page.locator('#cxEncounterOut').innerText()).includes('XP ajustado'),'Calculadora do DMG calcula XP ajustado');
  check(errors.length===0,'Navegação sem exceções JS: '+errors.slice(0,2).join('|'));
  const tooWide=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+14);
  check(!tooWide,'Sem overflow horizontal grave em '+viewport.width);
  await context.close();
 }
 await browser.close();console.log('OK - '+tests+' verificações concluídas');
})().catch(e=>{console.error('FAIL',e.stack||e);process.exit(1)});